<?php
/**
 * JcbInOut - Phase 1 report
 *
 * Renders jcb-metamodel.json as a readable Markdown summary: the explicit
 * statement of what a JCB blueprint contains, and what it deliberately omits.
 *
 * Usage: php report-metamodel.php <metamodel.json> [out.md]
 */

declare(strict_types=1);

$metaFile = $argv[1] ?? (__DIR__ . '/../jcb-metamodel.json');
$outFile  = $argv[2] ?? (__DIR__ . '/../METAMODEL.md');

$meta     = json_decode((string) file_get_contents($metaFile), true);
$entities = $meta['entities'];
$stats    = $meta['stats'];

$kindLabel = [
	'property'        => 'property',
	'reference'       => 'reference (guid)',
	'reference_local' => 'reference (local id)',
	'containment'     => 'containment (subform)',
	'structured'      => 'json blob',
	'secret'          => 'encrypted',
];

$out   = [];
$out[] = '# JCB metamodel (derived)';
$out[] = '';
$out[] = 'Generated by `' . $meta['meta']['generator'] . '` v' . $meta['meta']['generatorVersion']
	. ' from JCB `' . substr($meta['meta']['jcbCommit'], 0, 10) . '`.';
$out[] = '';
$out[] = 'This is a **derived** document. It is read out of JCB\'s own sources by reflection';
$out[] = '(`Table.php`, `Factory.php`, the per-entity `Remote\Config` classes) and regenerated';
$out[] = 'per JCB version. It is not hand-maintained and should never be edited directly.';
$out[] = '';

// -- summary ---------------------------------------------------------------
$out[] = '## Summary';
$out[] = '';
$out[] = '| | |';
$out[] = '|---|---|';
$out[] = '| Entity types defined | ' . $stats['entitiesTotal'] . ' |';
$out[] = '| Entity types portable (in blueprints) | ' . $stats['entitiesPortable'] . ' |';
$out[] = '| Properties total | ' . $stats['propertiesTotal'] . ' |';
$out[] = '';
$out[] = '### Properties by feature kind';
$out[] = '';
$out[] = '| Kind | Count | Becomes (LionWeb) |';
$out[] = '|---|---:|---|';

$lionweb = [
	'property'        => '`Property`',
	'reference'       => '`Reference`',
	'reference_local' => '*excluded* - not portable',
	'containment'     => '`Containment` + row `Concept`',
	'structured'      => '`Property : JsonBlob` (lossy)',
	'secret'          => '*excluded* - installation-local',
];

foreach ($stats['byKind'] as $kind => $n)
{
	$out[] = '| ' . ($kindLabel[$kind] ?? $kind) . ' | ' . $n . ' | ' . ($lionweb[$kind] ?? '') . ' |';
}

$out[] = '';

// -- non-portable ----------------------------------------------------------
$nonPortable = array_keys(array_filter($entities, static fn($e) => !$e['portable']));

$out[] = '## Not portable';
$out[] = '';
$out[] = 'These entity types exist in JCB\'s schema but are absent from the transport';
$out[] = 'catalogue. They are installation-local and never appear in a blueprint:';
$out[] = '';

foreach ($nonPortable as $e)
{
	$out[] = '- `' . $e . '`';
}

$out[] = '';

// -- entity table ----------------------------------------------------------
$out[] = '## Entity types';
$out[] = '';
$out[] = '| Entity | Portable | Props | Refs | Subforms | Children | Excluded |';
$out[] = '|---|:---:|---:|---:|---:|---|---:|';

ksort($entities);

foreach ($entities as $name => $e)
{
	$props = $e['properties'] ?? [];
	$refs  = count(array_filter($props, static fn($p) => $p['kind'] === 'reference'));
	$subs  = count(array_filter($props, static fn($p) => $p['kind'] === 'containment'));
	$excl  = count(array_filter($props, static fn($p) => !$p['portable']));
	$kids  = $e['transport']['children'] ?? [];

	$out[] = sprintf('| `%s` | %s | %d | %d | %d | %s | %d |',
		$name,
		$e['portable'] ? 'yes' : 'no',
		count($props),
		$refs,
		$subs,
		$kids ? '`' . implode('`, `', $kids) . '`' : '-',
		$excl
	);
}

$out[] = '';

// -- occurrences -----------------------------------------------------------
$out[] = '## Occurrence concepts';
$out[] = '';
$out[] = 'Subforms whose rows carry a reference *plus* use-site settings are the';
$out[] = 'definition/occurrence split as it actually exists in JCB data. Each becomes';
$out[] = 'its own LionWeb concept rather than a copy of the referenced definition.';
$out[] = '';
$out[] = '| Row concept | Owner | Property | References | Setting fields |';
$out[] = '|---|---|---|---|---:|';

foreach ($entities as $name => $e)
{
	foreach ($e['properties'] ?? [] as $pname => $p)
	{
		if ($p['kind'] !== 'containment' || empty($p['subform']['rowConcept']))
		{
			continue;
		}

		$fields  = $p['subform']['fields'] ?? [];
		$targets = [];

		foreach ($fields as $f)
		{
			if (($f['kind'] ?? '') === 'reference' && !empty($f['target']))
			{
				$targets[$f['target']] = true;
			}
		}

		if ($targets === [])
		{
			continue;   // a plain nested record, not an occurrence
		}

		$out[] = sprintf('| `%s` | `%s` | `%s` | `%s` | %d |',
			$p['subform']['rowConcept'], $name, $pname,
			implode('`, `', array_keys($targets)),
			count($fields) - count($targets)
		);
	}
}

$out[] = '';

// -- diagnostics -----------------------------------------------------------
$out[] = '## Open issues';
$out[] = '';
$out[] = 'Points where JCB\'s sources are ambiguous or incomplete. Each needs a Phase 2';
$out[] = 'decision; several are worth reporting upstream.';
$out[] = '';

$grouped = [];

foreach ($meta['diagnostics'] as $d)
{
	$grouped[$d['severity']][$d['code']][] = $d['message'];
}

foreach (['error', 'warning', 'info'] as $sev)
{
	if (empty($grouped[$sev]))
	{
		continue;
	}

	$out[] = '### ' . ucfirst($sev);
	$out[] = '';

	foreach ($grouped[$sev] as $code => $messages)
	{
		$out[] = '**`' . $code . '`** (' . count($messages) . ')';
		$out[] = '';

		foreach (array_slice($messages, 0, 6) as $m)
		{
			$out[] = '- ' . $m;
		}

		if (count($messages) > 6)
		{
			$out[] = '- *(' . (count($messages) - 6) . ' more)*';
		}

		$out[] = '';
	}
}

file_put_contents($outFile, implode("\n", $out) . "\n");
fwrite(STDERR, "Wrote {$outFile}\n");
